];

class Run {
  Run(this.reads, this.bytes, this.found, this.extent, this.cpuMs, this.netMs);
  final int reads, bytes, found;
  final double extent, cpuMs, netMs;
}

Future<Run> measure(List<String> dirs, double lat, double lng) async {
  final cpuReader = FileCellReader(dirs);
  final sw = Stopwatch()..start();
  final a = FirestoreCellSource(
    reader: cpuReader,
    misses: MemoryCellMissCache(),
  ).area(latitude: lat, longitude: lng);
  await a.ensure(50);
  final cpu = sw.elapsedMicroseconds / 1000;

  final netReader = FileCellReader(dirs, latency: _rtt);
  sw.reset();
  await FirestoreCellSource(
    reader: netReader,
    misses: MemoryCellMissCache(),
  ).area(latitude: lat, longitude: lng).ensure(50);
  final net = sw.elapsedMicroseconds / 1000;

  return Run(
    cpuReader.reads,
    cpuReader.bytes,
    a.records.length,
    a.extentMeters ?? 0,
    cpu,
    net,
  );
}

double pct(List<double> v, double p) {
  final s = [...v]..sort();
  return s[math.min(s.length - 1, (p * s.length).floor())];
}

void main() {
  final dirs = [
    for (final a in ['california', 'new_jersey']) '$_root/$a',
  ];
  final available = dirs.every((d) => Directory('$d/cells').existsSync());
  final env = Platform.environment;
  final asked = env['CELL_BENCHMARK'] == '1' || env['WRITE_BENCHMARK'] == '1';

  test(
    'nearest-50 on real Overture cells',
    () async {
      final out = StringBuffer()
        ..writeln('# Nearest-50 benchmark (real Overture cells)')
        ..writeln()
        ..writeln(
          'Generated by `test/benchmark/cell_benchmark_test.dart` on the '
          'California + New Jersey cell files (release 2026-10-21.0), with '
          "the app's own `CellArea`. Reads = cold Firestore document reads; "
          'a repeat visit reads 0 (device cache). Net time adds a simulated '
          '100 ms per document round trip.',
        )
        ..writeln()
        ..writeln(
          '| Place | Kind | Homes | Farthest (m) | Reads | KB | CPU ms '
          '| With 100 ms RTT |',
        )
        ..writeln('|---|---|---:|---:|---:|---:|---:|---:|');

      // Warm up the isolate pool / JIT.
      await measure(dirs, places.first.lat, places.first.lng);

      for (final p in places) {
        final r = await measure(dirs, p.lat, p.lng);
        out.writeln(
          '| ${p.name} | ${p.kind} | ${r.found} | ${r.extent.round()} '
          '| ${r.reads} | ${(r.bytes / 1024).round()} '
          '| ${r.cpuMs.round()} | ${r.netMs.round()} ms |',
        );
      }

      // 200 random real homes as user locations (deterministic).
      final rnd = math.Random(42);
      final files = [
        for (final d in dirs)
          ...Directory('$d/cells').listSync().whereType<File>(),
      ];
      final reads = <double>[], kb = <double>[], cpu = <double>[];
      final net = <double>[], extent = <double>[];
      var under50 = 0;
      var n = 0;
      while (n < 200) {
        final f = files[rnd.nextInt(files.length)];
        final body =
            jsonDecode(utf8.decode(gzip.decode(f.readAsBytesSync()))) as Map;
        final homes = body['h'] as List?;
        if (homes == null || homes.isEmpty) continue;
        final h = homes[rnd.nextInt(homes.length)] as Map;
        final r = await measure(
          dirs,
          (h['a'] as num).toDouble(),
          (h['o'] as num).toDouble(),
        );
        reads.add(r.reads.toDouble());
        kb.add(r.bytes / 1024);
        cpu.add(r.cpuMs);
        net.add(r.netMs);
        extent.add(r.extent);
        if (r.found < 50) under50++;
        n++;
      }
      String row(String name, List<double> v, [int dp = 0]) =>
          '| $name | ${pct(v, .5).toStringAsFixed(dp)} '
          '| ${pct(v, .9).toStringAsFixed(dp)} '
          '| ${pct(v, .99).toStringAsFixed(dp)} '
          '| ${v.reduce(math.max).toStringAsFixed(dp)} |';
      out
        ..writeln()
        ..writeln('## 200 random homes as starting points')
        ..writeln()
        ..writeln('| Metric | Median | p90 | p99 | Max |')
        ..writeln('|---|---:|---:|---:|---:|')
        ..writeln(row('Cold reads', reads))
        ..writeln(row('Downloaded KB', kb))
        ..writeln(row('CPU ms', cpu))
        ..writeln(row('With 100 ms RTT, ms', net))
        ..writeln(row('Farthest of the 50, m', extent))
        ..writeln()
        ..writeln('Fewer than 50 homes found: $under50 of 200.');

      // ignore: avoid_print
      print(out);
      if (Platform.environment['WRITE_BENCHMARK'] == '1') {
        File('docs/performance/cell_benchmark.md').writeAsStringSync('$out');
      }
    },
    skip: !asked
        ? 'set CELL_BENCHMARK=1 to run (about 1 minute)'
        : available
        ? false
        : 'cell files not built (tool/overture_cells)',
    timeout: const Timeout(Duration(minutes: 10)),
  );
}
