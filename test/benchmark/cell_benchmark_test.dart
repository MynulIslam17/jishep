// Nearest-50 benchmark on the REAL Overture cell files built by
// tool/overture_cells (out/california, out/new_jersey), using the app's own
// FirestoreCellSource + CellArea. Skipped when the files aren't there.
//
//   CELL_BENCHMARK=1 flutter test test/benchmark/cell_benchmark_test.dart
//   WRITE_BENCHMARK=1 flutter test test/benchmark/cell_benchmark_test.dart
//
// "Reads" are cold Firestore document reads (what Firestore bills). Bytes
// are the gz payloads downloaded. Time is measured twice: client CPU only,
// and with a simulated 100 ms network round trip per document (parallel
// reads overlap, as they do in the app), which shows sequential trips.
@Tags(['benchmark'])
library;

import 'dart:convert';
import 'dart:io';
import 'dart:math' as math;

import 'package:flutter_test/flutter_test.dart';
import 'package:gps_cielo/core/data/cell_source.dart';

const _root = 'tool/overture_cells/out';
const _rtt = Duration(milliseconds: 100);

class FileCellReader implements CellReader {
  FileCellReader(this.dirs, {this.latency = Duration.zero});
  final List<String> dirs;
  final Duration latency;
  int reads = 0;
  int bytes = 0;

  @override
  Future<Map<String, dynamic>?> fromCache(String prefix) async => null;

  @override
  Future<Map<String, dynamic>?> fromServer(String prefix) async {
    reads++;
    if (latency > Duration.zero) await Future<void>.delayed(latency);
    for (final d in dirs) {
      final f = File('$d/cells/$prefix.json.gz');
      if (!f.existsSync()) continue;
      final gz = f.readAsBytesSync();
      bytes += gz.length;
      final body = jsonDecode(utf8.decode(gzip.decode(gz))) as Map;
      if (body['split'] != null) {
        return {'v': body['v'], 'split': body['split'], 'n': 0};
      }
      return {'v': body['v'], 'h': gz};
    }
    return null;
  }
}

typedef Place = ({String name, String kind, double lat, double lng});

const places = <Place>[
