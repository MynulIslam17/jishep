  (name: 'San Francisco', kind: 'dense', lat: 37.7749, lng: -122.4194),
  (name: 'Newark NJ', kind: 'dense', lat: 40.7357, lng: -74.1724),
  (name: 'Jersey City NJ', kind: 'dense', lat: 40.7178, lng: -74.0431),
  (name: 'Fresno', kind: 'suburban', lat: 36.7378, lng: -119.7871),
  (name: 'Spring Valley', kind: 'suburban', lat: 32.7448, lng: -116.9989),
  (name: 'Princeton NJ', kind: 'suburban', lat: 40.3573, lng: -74.6672),
  (name: 'Bishop', kind: 'rural', lat: 37.3635, lng: -118.3951),
  (name: 'Needles', kind: 'rural', lat: 34.8481, lng: -114.6141),
