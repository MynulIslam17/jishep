// Neighborhood search benchmark: legacy geoflutterfire `fetchWithin` vs the
// progressive GeoSearch, on deterministic synthetic Dhaka data.
//
//   flutter test test/benchmark/geo_benchmark_test.dart
//
// Reads are counted the way Firestore bills them (documents returned + 1 per
// empty query) against an in-memory model of the same indexed query, so
// they are exact. Wall time is client CPU only (no network): network cost
// is reported as sequential round trips. Results: docs/performance/.
@Tags(['benchmark'])
library;

import 'dart:io';

import 'package:flutter_test/flutter_test.dart';
import 'package:gps_cielo/core/data/geo_search.dart';

import '../support/synthetic_households.dart';

/// geoflutterfire_plus 0.0.34 `geohashDigitsFromRadius`.
int legacyPrecision(double km) {
  if (km <= 0.00477) return 9;
  if (km <= 0.0382) return 8;
  if (km <= 0.153) return 7;
  if (km <= 1.22) return 6;
  if (km <= 4.89) return 5;
  if (km <= 39.1) return 4;
  if (km <= 156) return 3;
  if (km <= 1250) return 2;
  return 1;
}

void main() {
  test('benchmark', () async {
    final out = StringBuffer()
      ..writeln('# Neighborhood search benchmark')
      ..writeln()
      ..writeln(
        'Generated by `test/benchmark/geo_benchmark_test.dart` '
        '(deterministic seed 42). Reads = Firestore billed reads.',
      )
      ..writeln()
      ..writeln(
        '| Households | Area | Range | In range | Legacy reads '
        '(any page) | New: first 10 (reads / trips) | New: 25 | New: whole '
        'range | Exact vs brute force | Docs read twice |',
      )
      ..writeln('|---:|---|---:|---:|---:|---:|---:|---:|---|---:|');

    const centers = [
      (23.7286, 90.4182, 'dense'),
      (23.7460, 90.3760, 'medium'),
      (23.6900, 90.5000, 'sparse'),
    ];

    for (final n in const [100, 1000, 10000, 100000]) {
      final data = syntheticHouseholds(n);
      for (final (lat, lng, area) in centers) {
        for (final km in const [1.0, 5.0]) {
          final index = IndexedHouseholds(data);
          final legacy = index.legacyReads(lat, lng, km, legacyPrecision(km));

          final seen = <String>{};
          var twice = 0;
          Future<List<GeoDoc>> counted(
            String p, {
            required int limit,
            GeoDoc? startAfter,
          }) async {
            final docs = await index.query(
              p,
              limit: limit,
              startAfter: startAfter,
            );
            for (final d in docs) {
              if (!seen.add(d.id)) twice++;
            }
            return docs;
          }

          final search = GeoSearch(
            query: counted,
            latitude: lat,
            longitude: lng,
            maxMeters: km * 1000,
          );
          await search.ensure(10);
          final r10 = search.stats.billedReads, t10 = search.stats.roundTrips;
          await search.ensure(25);
          final r25 = search.stats.billedReads;
          final watch = Stopwatch()..start();
          await search.loadAll();
          watch.stop();
          final got = [for (final h in search.confirmed) h.doc.id];
          final expected = bruteForceNearest(data, lat, lng, km * 1000);
          final exact = _listEq(got, expected);
          expect(exact, isTrue, reason: '$n $area $km km');
          expect(twice, 0, reason: 'no document read twice');

          out.writeln(
            '| $n | $area | $km km | ${expected.length} | $legacy | '
            '$r10 / $t10 | $r25 | ${search.stats.billedReads} '
            '(${search.stats.roundTrips} trips, ${watch.elapsedMilliseconds} ms CPU) | '
            '${exact ? 'yes' : 'NO'} | $twice |',
          );
        }
      }
    }
    final file = File('docs/performance/geo_benchmark.md')
      ..createSync(recursive: true);
    file.writeAsStringSync(out.toString());
    // ignore: avoid_print
    print(out);
  }, timeout: const Timeout(Duration(minutes: 10)));
}

bool _listEq(List<String> a, List<String> b) {
  if (a.length != b.length) return false;
  for (var i = 0; i < a.length; i++) {
    if (a[i] != b[i]) return false;
  }
  return true;
}
